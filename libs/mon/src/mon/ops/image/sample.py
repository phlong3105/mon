@UPSAMPLERS.register(name="interpolation")
class InterpolationUpsample(ImageUpsampler):
    """Interpolation model for super-resolution."""

    # --- Lifecycle & Initialization ---
    def __init__(self, backend: Backend = Backend.CV2, *args, **kwargs):
        """Initialize a new instance.

        Args:
            backend (Backend, optional): Backend to use for image resizing.
                Can be either 'cv2' for OpenCV or 'torchvision' for PyTorch's
                torchvision. Defaults to Backend.CV2.
            verbose (bool, optional): Verbosity mode. Defaults to True.
        """
        super().__init__()

        # Assign attributes
        self.backend = Backend(backend)

    # --- Callable & Context Manager ---
    @override
    def __call__(self, x_lr: TensorOrArray, imgsz: Size, *args, **kwargs) -> TensorOrArray:
        """Upsample the input low-resolution image using the provided
        high-resolution.

        Args:
            x_lr (TensorOrArray): Low-resolution image, formatted as a tensor
                of shape (B, C, H1, W1) and values ranging from 0.0 to 1.0;
                or as an array of shape (H1, W1, C) and values ranging from 0 to 255.
            imgsz (Size): Size of the high-resolution image.

        Returns:
            TensorOrArray: Upscaled image, formatted as a tensor of shape
                (B, C, H2, W2) and values ranging from 0.0 to 1.0; or as an
                array of shape (H1, W1, C) and values ranging from 0 to 255.
        """
        # Normalize input
        imgsz = Size.from_value(imgsz)

        # 1. Numpy / OpenCV
        if self.backend == Backend.CV2:
            if isinstance(x_lr, Tensor):
                x_lr = to_image_array(x_lr)
            _, _, c = x_lr.shape
            is_depth = (c == 1)
            mode = cv2.INTER_NEAREST if is_depth else cv2.INTER_CUBIC
            x_hr = cv2.resize(src=x_lr, dsize=imgsz.wh, interpolation=mode)

        # 2. Tensor / TorchVision
        elif self.backend == Backend.TORCHVISION:
            if isinstance(x_lr, ndarray):
                x_lr = to_image_tensor(x_lr)
            _, c, _, _ = x_lr.shape
            is_depth = (c == 1)
            mode = InterpolationMode.NEAREST_EXACT if is_depth else InterpolationMode.BICUBIC
            x_hr = F_tv.resize(
                img=x_lr,
                size=list(imgsz.hw),
                interpolation=mode,
                antialias=False,
            )

        # 3. Error: Unsupported backend
        else:
            raise ValueError(
                f"Expected 'x_lr' to be a tensor or ndarray, "
                f"but got {type(x_lr).__name__}."
            )

        return x_hr


@UPSAMPLERS.register(name="guided_filter")
class GuidedFilterUpsample(ImageUpsampler):
    """Guided Filter Upsample model for super-resolution tasks."""

    # --- Lifecycle & Initialization ---
    def __init__(self, radius: int = 1, *args, **kwargs):
        """Initialize a new instance.

        Args:
            radius (int, optional): Radius for the guided filter. Defaults to 1.
        """
        super().__init__()

        # Assign attributes
        self.radius = radius

    # --- Callable & Context Manager ---
    @override
    def __call__(
        self,
        x_lr: Tensor,
        y_hr: Tensor,
        y_lr: Tensor | None = None,
        *args, **kwargs
    ) -> TensorOrArray:
        """Upsample the input low-resolution image using the provided
        high-resolution.

        Args:
            x_lr (Tensor): Low-resolution upscaling image of shape (B, C, H1, W1)
                and values ranging from 0.0 to 1.0.
            y_hr (Tensor): High-resolution guidance image of shape (B, C, H2, W2)
                and values ranging from 0.0 to 1.0.
            y_lr (Tensor, optional): Low-resolution guidance image of shape
                (B, C, H1, W1) and values ranging from 0.0 to 1.0. If None, it will
                be generated by downsampling ``y_hr`` to match the shape of ``x_lr``.
                Defaults to None.

        Returns:
            Tensor: Upscaled image of shape (B, C, H2, W2) and values ranging
                from 0.0 to 1.0.
        """
        return guided_filter_upsample(x_lr=x_lr, y_lr=y_lr, y_hr=y_hr, r=self.radius)

