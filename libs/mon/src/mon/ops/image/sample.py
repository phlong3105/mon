class ImageUpsampler(ABC):
    """Base class for image upsamplers."""

    # --- Callable & Context Manager ---
    @abstractmethod
    def __call__(
        self,
        x_lr: TensorOrArray,
        y_hr: TensorOrArray,
        y_lr: TensorOrArray | None = None,
        *args, **kwargs
    ) -> TensorOrArray:
        """Upsample the input low-resolution image using the provided
        high-resolution.

        Args:
            x_lr (TensorOrArray): Low-resolution image, formatted as a tensor
                of shape (B, C, H1, W1) and values ranging from 0.0 to 1.0;
                or as an array of shape (H1, W1, C) and values ranging from 0 to 255.
            y_hr (TensorOrArray): High-resolution guidance image, formatted as
                a tensor of shape (B, C, H2, W2) and values ranging from 0.0 to 1.0;
                or as an array of shape (H1, W1, C) and values ranging from 0 to 255.
            y_lr (Tensor, optional): Low-resolution guidance image, formatted
                as a tensor of shape (B, C, H1, W1) and values ranging from 0.0 to 1.0;
                or as an array of shape (H1, W1, C) and values ranging from 0 to 255.
                If None, it will be generated by downsampling ``y_hr`` to match
                the shape of ``x_lr``. Defaults to None.

        Returns:
            TensorOrArray: Upscaled image, formatted as a tensor of shape
                (B, C, H2, W2) and values ranging from 0.0 to 1.0; or as an
                array of shape (H1, W1, C) and values ranging from 0 to 255.
        """
        pass

